import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.waitForTimeout(1800);
await page.screenshot({path:'../.reference/replica-desktop.png'});
console.log('Desktop:',await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,hero:document.querySelector('.hero').offsetHeight,fonts:document.fonts.check('800 80px Sora')})));
await page.locator('#journey').evaluate(el=>scrollTo({top:el.offsetTop+2400,behavior:'instant'}));
await page.waitForTimeout(3000);
await page.screenshot({path:'../.reference/replica-journey.png'});
await page.locator('#products').evaluate(el=>scrollTo({top:el.offsetTop-74,behavior:'instant'}));
await page.waitForTimeout(800);
await page.screenshot({path:'../.reference/replica-products.png'});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.waitForTimeout(1200);
await page.screenshot({path:'../.reference/replica-mobile.png'});
console.log('Mobile:',await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth})));
await page.locator('#contact').evaluate(el=>scrollTo({top:el.offsetTop,behavior:'instant'}));
await page.waitForTimeout(800);
await page.screenshot({path:'../.reference/replica-contact-mobile.png'});
await page.goto('http://127.0.0.1:5173/blog.html',{waitUntil:'networkidle'});
await page.waitForTimeout(800);
await page.screenshot({path:'../.reference/replica-blog-mobile.png'});
console.log('Errors:',JSON.stringify(errors));
await browser.close();
